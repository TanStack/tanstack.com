import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.dirname(
  fileURLToPath(import.meta.resolve('@phosphor-icons/react/package.json')),
)
const iconNames = readdirSync(path.join(packageRoot, 'dist/csr'))
  .filter((fileName) => fileName.endsWith('.es.js'))
  .map((fileName) => fileName.slice(0, -'.es.js'.length))
  .sort((a, b) => a.localeCompare(b))
const getLocalName = (iconName) =>
  iconName === 'Infinity' ? 'InfinityIcon' : iconName
const getImportSpecifier = (iconName) => {
  const localName = getLocalName(iconName)
  return localName === iconName ? iconName : `${iconName} as ${localName}`
}

const imports = iconNames
  .map(
    (iconName) =>
      `import { ${getImportSpecifier(iconName)} } from '@phosphor-icons/react/${iconName}'`,
  )
  .join('\n')
const entries = iconNames
  .map(
    (iconName) => `  { name: '${iconName}', Cmp: ${getLocalName(iconName)} },`,
  )
  .join('\n')

const output = `// Generated by scripts/generate-phosphor-icon-registry.mjs.
// Importing individual icon modules keeps this registry out of the shared
// @phosphor-icons/react barrel used by the rest of the site.
import type { Icon } from '@phosphor-icons/react'
${imports}

export const phosphorIconRegistry: ReadonlyArray<{
  name: string
  Cmp: Icon
}> = [
${entries}
]
`

writeFileSync(
  path.join(process.cwd(), 'src/components/ds/phosphor-icons.generated.ts'),
  output,
)
